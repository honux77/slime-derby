let currentLang = 'ko';

function t(key) {
    return TRANSLATIONS[currentLang][key] || key;
}

function setLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('slimeDerbyLang', lang);
    updateAllText();
}

function loadLanguage() {
    const saved = localStorage.getItem('slimeDerbyLang');
    if (saved && TRANSLATIONS[saved]) {
        currentLang = saved;
    }
}

